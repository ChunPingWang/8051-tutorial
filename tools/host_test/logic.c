/*============================================================================
 * logic.c ─ 可在「電腦上」測試的純邏輯函式
 *============================================================================
 * 觀念:微控制器的程式常常和硬體綁死(SBUF、ADCRH…),沒辦法在 PC 上跑。
 *       但其中「不碰硬體的純計算邏輯」可以抽出來,在電腦上用一般 C 編譯器
 *       快速測試。這樣你改演算法時,不必每次都燒到板子才知道對不對。
 *
 * 這裡抽出兩個範例用到的純邏輯:
 *   1. uint_to_dec : 把整數轉成十進位字串(同 c/04-uart 的輸出邏輯)
 *   2. adc_to_mv   : 把 12 位元 ADC 值換算成毫伏(同 docs/06 的電壓公式)
 *
 * 編譯測試:見同資料夾 Makefile → make test
 *===========================================================================*/

#include "logic.h"

/* 把 0~65535 的整數轉成十進位字串,結果寫進 out(呼叫端需保證至少 6 bytes)*/
void uint_to_dec(unsigned int n, char *out)
{
    char buf[6];
    int i = 0, j = 0;

    if (n == 0) {           /* 0 要特別處理,否則下面的 while 不會跑 */
        out[0] = '0';
        out[1] = '\0';
        return;
    }
    while (n > 0) {         /* 先從個位數開始取,結果是反的 */
        buf[i++] = (char)('0' + (n % 10));
        n /= 10;
    }
    while (i > 0)           /* 再反過來寫出去,就是正確順序 */
        out[j++] = buf[--i];
    out[j] = '\0';
}

/* 把 12 位元 ADC 值 (0~4095) 換算成毫伏;vdd_mv 是供電電壓(例如 3300 = 3.3V)*/
unsigned int adc_to_mv(unsigned int adc, unsigned int vdd_mv)
{
    /* 用 long 避免乘法溢位(4095 × 3300 會超過 16 位元)*/
    return (unsigned int)((unsigned long)adc * vdd_mv / 4095UL);
}
