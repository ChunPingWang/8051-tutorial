;=============================================================================
; 第 3 課:計時器中斷 ─ 精準閃爍  ─  組合語言版
;=============================================================================
; 與 C 版 (c/03-timer) 做的事完全一樣:P1.4 的 LED 每 0.5 秒翻轉一次。
;
; 重點對照 C 版:
;   - 中斷向量要自己在 0x000B 放一行 ljmp 跳到 ISR
;   - ISR 開頭 push 保存、結尾 pop 還原暫存器,最後用 reti(不是 ret!)
;   - 16 位元的計數器用兩個記憶體位元組 (cnt_lo / cnt_hi) 湊出來
;
; 預載值 0xC180 = 每 1ms 溢位一次;數滿 500 (=0x01F4) 次就翻轉 LED。
;=============================================================================

    .module timer

    ; ---- SFR 位址 ----
    P1M1  =  0xB3
    P1M2  =  0xB4
    TMOD  =  0x89
    CKCON =  0x8E
    TL0   =  0x8A
    TH0   =  0x8C
    ; ---- 可定址的位元 ----
    LED   =  0x94          ; P1.4
    TR0   =  0x8C          ; TCON.4 啟動 Timer0
    ET0   =  0xA9          ; IE.1  Timer0 中斷致能
    EA    =  0xAF          ; IE.7  總中斷

    ; ---- 自己配置的 RAM 變數(內部 RAM 一般區)----
    cnt_lo = 0x30          ; 16 位元計數器低位元組
    cnt_hi = 0x31          ; 16 位元計數器高位元組

;-----------------------------------------------------------------------------
; 向量區
;-----------------------------------------------------------------------------
    .area CODE (ABS,CODE)
    .org  0x0000
    ljmp  start            ; 重置向量
    .org  0x000B
    ljmp  timer0_isr       ; Timer0 中斷向量

;-----------------------------------------------------------------------------
; 主程式
;-----------------------------------------------------------------------------
start:
    ; P1.4 → 推挽輸出
    anl   P1M1, #0xEF
    orl   P1M2, #0x10

    ; 計數器歸零
    mov   cnt_lo, #0x00
    mov   cnt_hi, #0x00

    ; 設定 Timer0:模式1、用 16MHz、裝預載值
    mov   TMOD,  #0x01      ; Timer0 模式 1(16 位元)
    orl   CKCON, #0x08      ; T0M = 1,Timer0 用完整 16MHz
    mov   TH0,   #0xC1
    mov   TL0,   #0x80

    setb  ET0               ; 開 Timer0 中斷
    setb  EA                ; 開總中斷
    setb  TR0               ; 啟動 Timer0

main_loop:
    sjmp  main_loop         ; 主程式空轉,LED 由中斷在背景翻轉

;-----------------------------------------------------------------------------
; Timer0 中斷服務程式
;-----------------------------------------------------------------------------
timer0_isr:
    push  acc               ; 保存會用到的暫存器
    push  psw

    mov   TH0, #0xC1        ; 重新裝填預載值
    mov   TL0, #0x80

    ; 16 位元計數器 +1:cnt_lo 先加,進位再加到 cnt_hi
    mov   A, cnt_lo
    add   A, #1
    mov   cnt_lo, A
    mov   A, cnt_hi
    addc  A, #0             ; 把低位加法的進位 (CY) 帶上來
    mov   cnt_hi, A

    ; 判斷是否數到 500 (0x01F4)
    mov   A, cnt_lo
    cjne  A, #0xF4, isr_done   ; 低位元組 != 0xF4 → 還沒到
    mov   A, cnt_hi
    cjne  A, #0x01, isr_done   ; 高位元組 != 0x01 → 還沒到

    ; 數到 500:計數器歸零,翻轉 LED
    mov   cnt_lo, #0x00
    mov   cnt_hi, #0x00
    cpl   LED               ; 翻轉 P1.4

isr_done:
    pop   psw               ; 還原暫存器
    pop   acc
    reti                    ; 中斷返回(務必用 reti)
