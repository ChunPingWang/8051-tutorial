;=============================================================================
; 第 1 課:LED 閃爍 (Blink)  ─  組合語言版 (SDCC / sdas8051 語法)
;=============================================================================
; 與 C 版 (c/01-blink) 做的事完全一樣,方便你左右對照。
;
; 接線:P1.4 ──► 220Ω ──► LED(長腳) ,LED(短腳)──► GND
;       P1.4 = 高電位 → LED 亮;低電位 → 滅。
;
; 組語小抄:
;   = (等號)   定義一個符號常數(把名字對應到數字)
;   .area      宣告一個程式/資料「區段」
;   .org       指定接下來的程式碼要放在哪個位址
;   #          後面接「立即值」(常數本身),沒有 # 則代表「位址」
;   anl/orl    位元 AND / OR(對應 C 的 & / |)
;   setb/clr   把某個 bit 設為 1 / 清為 0
;   djnz       減 1,不為 0 就跳(做迴圈用)
;   sjmp/ljmp  短跳 / 長跳
;=============================================================================

    .module blink

; ---- 把會用到的 SFR 名稱對應到它的位址(等同 C 的 N76E003.h)----
    P1M1  =  0xB3           ; Port1 模式暫存器 1
    P1M2  =  0xB4           ; Port1 模式暫存器 2
    LED   =  0x94           ; P1.4 的「位元位址」

;-----------------------------------------------------------------------------
; 重置向量:晶片一通電,程式一定從位址 0x0000 開始執行。
; 我們在這裡放一行「長跳躍」直接跳到主程式 start。
;-----------------------------------------------------------------------------
    .area CODE (ABS,CODE)
    .org  0x0000
    ljmp  start            ; 一通電就跳到主程式

;-----------------------------------------------------------------------------
; 主程式
;-----------------------------------------------------------------------------
start:
    ; 設定 P1.4 為推挽輸出:P1M1.4=0、P1M2.4=1
    anl   P1M1, #0xEF       ; 1110 1111 → 把第 4 位清為 0
    orl   P1M2, #0x10       ; 0001 0000 → 把第 4 位設為 1

loop:
    setb  LED               ; P1.4 = 1 → LED 亮
    lcall delay
    clr   LED               ; P1.4 = 0 → LED 滅
    lcall delay
    sjmp  loop              ; 無窮迴圈

;-----------------------------------------------------------------------------
; 軟體延時副程式:三層巢狀 djnz,純粹消耗時間(不精準)。
; 改 R2 的值可調整延時長短。
;-----------------------------------------------------------------------------
delay:
    mov   R2, #20
d2:
    mov   R1, #0            ; #0 代表 256(0 先減 1 會變 255,共跑 256 次)
d1:
    mov   R0, #0
d0:
    djnz  R0, d0            ; 內層:數 256 下
    djnz  R1, d1            ; 中層:數 256 次
    djnz  R2, d2            ; 外層:數 20 次
    ret

; 註:SDCC 的 sdas8051 不需要(也不接受) .end 這個指令,直接結束即可。
