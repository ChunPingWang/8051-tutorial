;=============================================================================
; 第 2 課:按鈕控制 LED  ─  組合語言版
;=============================================================================
; 與 C 版 (c/02-button) 做的事完全一樣。
;
; 接線:
;   LED : P1.4 ──► 220Ω ──► LED(長腳),LED(短腳)──► GND
;   按鈕: P1.5 ──────[ 按鈕 ]────── GND   (用內部弱上拉)
;
;   按下 → P1.5 = 0 → LED 亮;放開 → P1.5 = 1 → LED 滅。
;
; 新指令:
;   jb  bit, 標籤   Jump if Bit:若該 bit = 1 就跳過去
;   jnb bit, 標籤   Jump if Not Bit:若該 bit = 0 就跳過去
;   → C 的 if/else,在組語裡就是「用位元判斷決定要不要跳」
;=============================================================================

    .module button

    P1M1  =  0xB3
    P1M2  =  0xB4
    LED   =  0x94          ; P1.4 位元位址
    SW    =  0x95          ; P1.5 位元位址

    .area CODE (ABS,CODE)
    .org  0x0000
    ljmp  start

start:
    ; P1.4 → 推挽輸出:P1M1.4=0、P1M2.4=1
    ; P1.5 → 準雙向  :P1M1.5=0、P1M2.5=0
    anl   P1M1, #0xCF      ; 1100 1111 → 把第 4、5 位都清為 0
    orl   P1M2, #0x10      ; 0001 0000 → P1M2.4 = 1(P1.4 推挽)
    anl   P1M2, #0xDF      ; 1101 1111 → P1M2.5 = 0(P1.5 準雙向)
    setb  SW               ; 讀取前先對準雙向腳寫 1

loop:
    jb    SW, led_off      ; 若 SW = 1(放開)→ 跳去關燈
    setb  LED              ; 否則(按下,SW=0)→ 開燈
    sjmp  loop
led_off:
    clr   LED              ; 關燈
    sjmp  loop
