;=============================================================================
; 第 4 課:UART 序列埠 ─ 讓晶片對電腦說話  ─  組合語言版
;=============================================================================
; 與 C 版 (c/04-uart) 做的事類似:每隔約 1 秒送出一行文字到序列埠。
; (為了讓組語版單純好懂,這裡送固定字串,不印遞增數字)
;
; 接線:P0.6 (TXD) ──► USB-TTL 的 RX;GND 共接。電腦端 9600 8N1。
;
; 新觀念:
;   - 字串放在程式記憶體 (CODE),用 movc A,@A+DPTR 一個一個讀出來
;   - DPTR 是 16 位元的「資料指標」,拿來指向字串
;=============================================================================

    .module uart

    ; ---- SFR ----
    P0M1  = 0xB1
    P0M2  = 0xB2
    SCON  = 0x98
    SBUF  = 0x99
    PCON  = 0x87
    TMOD  = 0x89
    CKCON = 0x8E
    T3CON = 0xC4
    TH1   = 0x8D
    TL1   = 0x8B
    ; ---- bits ----
    TR1   = 0x8E          ; TCON.6 啟動 Timer1
    TI    = 0x99          ; SCON.1 傳送完成旗標

    .area CODE (ABS,CODE)
    .org  0x0000
    ljmp  start

start:
    ; P0.6 / P0.7 設準雙向(清掉 P0M1、P0M2 的第 6、7 位)
    anl   P0M1, #0x3F      ; 0011 1111
    anl   P0M2, #0x3F

    ; UART0 模式1、Timer1 當鮑率產生器、9600 8N1
    mov   SCON,  #0x50     ; 模式1,REN=1
    anl   TMOD,  #0x0F     ; 清 Timer1 設定位
    orl   TMOD,  #0x20     ; Timer1 模式2(8 位元自動重載)
    orl   PCON,  #0x80     ; SMOD = 1(鮑率加倍)
    orl   CKCON, #0x10     ; T1M = 1(Timer1 吃滿 16MHz)
    anl   T3CON, #0xDF     ; BRCK = 0(鮑率來源選 Timer1)
    mov   TH1,   #0x98     ; 重載值 → 約 9600 bps
    mov   TL1,   #0x98
    setb  TR1              ; 啟動 Timer1

loop:
    mov   DPTR, #msg       ; DPTR 指向字串開頭
    lcall puts
    lcall delay
    sjmp  loop

;-----------------------------------------------------------------------------
; puts:送出 DPTR 指向的字串(以 0 結尾)
;-----------------------------------------------------------------------------
puts:
    clr   A
    movc  A, @A+DPTR       ; 從 CODE 讀一個字元到 A
    jz    puts_done        ; 讀到 0 → 字串結束
    lcall putc
    inc   DPTR             ; 指標往後移一個
    sjmp  puts
puts_done:
    ret

;-----------------------------------------------------------------------------
; putc:送出 A 裡的一個字元
;-----------------------------------------------------------------------------
putc:
    mov   SBUF, A          ; 把字元丟進傳送緩衝器
wait_ti:
    jnb   TI, wait_ti      ; 等傳送完成(TI=1)
    clr   TI               ; 清旗標
    ret

;-----------------------------------------------------------------------------
; delay:粗略延時約 1 秒
;-----------------------------------------------------------------------------
delay:
    mov   R2, #30
d2:
    mov   R1, #0
d1:
    mov   R0, #0
d0:
    djnz  R0, d0
    djnz  R1, d1
    djnz  R2, d2
    ret

;-----------------------------------------------------------------------------
; 要送的字串(放在程式記憶體)。\r\n = 0x0D 0x0A = 換行。
;-----------------------------------------------------------------------------
msg:
    .ascii "Hello from N76E003!"
    .db    0x0D, 0x0A, 0x00
