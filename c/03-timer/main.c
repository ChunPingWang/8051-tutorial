/*============================================================================
 * 第 3 課:計時器中斷 ─ 精準閃爍  ─  C 語言版
 *============================================================================
 * 學習目標:
 *   1. 設定 Timer0 為 16 位元模式,產生精準的 1ms 時間基準
 *   2. 用「中斷」讓 LED 在背景自動翻轉,主程式完全不用管
 *   3. 理解中斷服務程式 (ISR) 的寫法與注意事項
 *
 * 成果:P1.4 的 LED 每 0.5 秒翻轉一次(= 完整亮滅週期 1 秒),非常精準。
 *
 * 計時原理(詳見 docs/04-計時器與中斷.md):
 *   系統時脈 Fsys = 16MHz。設定 CKCON.T0M=1 讓 Timer0 直接用 16MHz,
 *   每數一下 = 1/16µs = 0.0625µs。
 *   想要每 1ms 溢位 → 要數 1000µs / 0.0625µs = 16000 下。
 *   預載值 = 65536 - 16000 = 49536 = 0xC180 → TH0=0xC1, TL0=0x80。
 *   ISR 每 1ms 進來一次,數滿 500 次(=500ms)就翻轉 LED。
 *===========================================================================*/

#include "N76E003.h"

#define LED   P14

/* 這個變數同時被「主程式」與「中斷」碰到,所以要加 volatile,
   告訴編譯器它隨時可能改變,不要做過度最佳化。 */
volatile unsigned int ms_count = 0;

/*----------------------------------------------------------------------------
 * Timer0 中斷服務程式 (ISR)
 *   __interrupt(1) 裡的 1 是 Timer0 的中斷編號(見 docs/04 的對照表)。
 *   SDCC 會自動幫我們:把 ISR 接到向量 0x000B、進出時保存暫存器、用 reti 返回。
 *   ISR 要「短」:這裡只做最必要的事(重載、計數、翻轉)。
 *---------------------------------------------------------------------------*/
void timer0_isr(void) __interrupt(1)
{
    TH0 = 0xC1;              /* 重新裝填預載值,下一次才會也是精準的 1ms */
    TL0 = 0x80;

    ms_count++;
    if (ms_count >= 500)     /* 1ms × 500 = 500ms = 0.5 秒 */
    {
        ms_count = 0;
        LED = !LED;          /* 翻轉 LED(亮變滅、滅變亮)*/
    }
}

void timer0_init(void)
{
    TMOD &= ~0x0F;           /* 清除 Timer0 的模式位 */
    TMOD |=  0x01;           /* Timer0 → 模式 1(16 位元)*/
    CKCON |= 0x08;           /* T0M = 1:Timer0 時脈用完整 Fsys(16MHz)*/

    TH0 = 0xC1;              /* 預載值高位元組 */
    TL0 = 0x80;              /* 預載值低位元組 */

    ET0 = 1;                 /* 開啟 Timer0 中斷(分開關)*/
    EA  = 1;                 /* 開啟總中斷(總開關)*/
    TR0 = 1;                 /* 啟動 Timer0 開始計數 */
}

void main(void)
{
    /* P1.4 → 推挽輸出 */
    P1M1 &= ~(1 << 4);
    P1M2 |=  (1 << 4);

    timer0_init();

    while (1)
    {
        /* 主程式這裡空空的,也能讓 LED 精準閃爍 ──
           因為翻轉的工作都交給中斷在背景做了。
           你可以在這裡放別的事情(例如讀按鈕),兩者互不影響! */
    }
}
