/*============================================================================
 * fsm.h ─ 「行人穿越號誌」狀態機的介面
 *============================================================================
 * 這個檔案(以及 fsm.c)完全不碰任何硬體暫存器,所以同一份原始碼:
 *   ‧ 可以用 SDCC 編進 N76E003 跑真的 LED 與按鈕 → c/07-fsm/main.c
 *   ‧ 也可以用電腦的 gcc 編起來模擬與測試       → tools/fsm_sim/、tools/host_test/
 *
 * 這就是狀態機最大的好處:把「決策邏輯」和「硬體」切開。
 * 原理與完整說明見 docs/11-狀態機.md。
 *===========================================================================*/
#ifndef FSM_H
#define FSM_H

/*----------------------------------------------------------------------------
 * 一、時間基準
 *---------------------------------------------------------------------------*/
/* 狀態機不認識「秒」,它只認識「我被敲了幾下」。每一下 = 100 毫秒。
   在 N76E003 上由 Timer0 中斷產生;在電腦模擬器上由 for 迴圈產生。 */
#define FSM_TICK_MS         100

/* 各狀態停留的時間,單位是 tick(1 tick = 100ms)*/
#define T_VEH_GREEN_MIN      50   /* 車道綠燈「最少」要維持 5.0 秒才理按鈕 */
#define T_VEH_YELLOW         30   /* 車道黃燈      3.0 秒 */
#define T_PED_WALK           80   /* 行人通行      8.0 秒 */
#define T_PED_FLASH          50   /* 行人催促(閃)5.0 秒 */
#define T_ALL_RED            20   /* 全紅淨空      2.0 秒 */

/* ticks 的上限:車道綠燈可能一整天沒人按,計數器不能無限加上去而溢位 */
#define FSM_TICKS_MAX     60000

/*----------------------------------------------------------------------------
 * 二、狀態(State)─ 系統「現在在哪個階段」
 *---------------------------------------------------------------------------*/
typedef enum {
    ST_VEH_GREEN = 0,   /* 車道綠燈:車子通行,行人紅燈(預設待機狀態) */
    ST_VEH_YELLOW,      /* 車道黃燈:準備停車 */
    ST_PED_WALK,        /* 行人通行:車道紅燈、行人綠燈、慢速「嗶」 */
    ST_PED_FLASH,       /* 行人催促:行人綠燈閃爍、急促「嗶」,快走! */
    ST_ALL_RED,         /* 全紅淨空:兩邊都紅,確保路口清空 */
    ST_COUNT            /* 狀態總數(方便寫迴圈與測試,不是真的狀態) */
} fsm_state_t;

/*----------------------------------------------------------------------------
 * 三、事件(Event)─ 從外界進來的「輸入」
 *---------------------------------------------------------------------------*/
typedef enum {
    EV_TICK = 0,        /* 時間過了 100ms(來自 Timer0 中斷) */
    EV_BUTTON           /* 行人按下按鈕(已經去過彈跳) */
} fsm_event_t;

/*----------------------------------------------------------------------------
 * 四、處理結果 ─ 同一個事件,在不同狀態下的「下場」不一樣
 *---------------------------------------------------------------------------*/
typedef enum {
    FSM_NO_CHANGE = 0,  /* 收到了,但什麼都不用做 */
    FSM_CHANGED,        /* 狀態換了! */
    FSM_RECORDED,       /* 事件被「記住」了(行人請求登記),但狀態還沒換 */
    FSM_IGNORED         /* 這個事件在目前狀態沒有意義,直接丟掉 */
} fsm_result_t;

/*----------------------------------------------------------------------------
 * 五、狀態機本體 ─ 它的「記憶」全都在這個結構裡
 *---------------------------------------------------------------------------*/
typedef struct {
    fsm_state_t  state;    /* 目前狀態 */
    unsigned int ticks;    /* 進入目前狀態後,已經過了幾個 tick */
    unsigned char request; /* 有沒有待處理的行人請求(1 = 有人按過了) */
} fsm_t;

/*----------------------------------------------------------------------------
 * 六、輸出(Output)─ 要讓硬體去做的事,打包成一份「快照」
 *---------------------------------------------------------------------------*/
/* 重點:狀態機不直接去碰 P1.0、P1.4…,它只填好這張表,
   由呼叫端(main.c 或模擬器)決定要點 LED、還是印在螢幕上。 */
typedef struct {
    unsigned char veh_red;      /* 車道紅燈 */
    unsigned char veh_yellow;   /* 車道黃燈 */
    unsigned char veh_green;    /* 車道綠燈 */
    unsigned char ped_red;      /* 行人紅燈 */
    unsigned char ped_green;    /* 行人綠燈 */
    unsigned char buzzer;       /* 蜂鳴器(選用) */
} fsm_out_t;

/*----------------------------------------------------------------------------
 * 七、三個函式,就是狀態機的全部
 *---------------------------------------------------------------------------*/
/* 開機初始化:回到安全的預設狀態(車道綠燈) */
void fsm_init(fsm_t *m);

/* 餵一個事件進去,狀態機自己決定要不要轉移。回傳處理結果。 */
fsm_result_t fsm_handle(fsm_t *m, fsm_event_t ev);

/* 依「目前狀態」算出該有的輸出。純函式:同樣的狀態一定得到同樣的輸出。 */
void fsm_outputs(const fsm_t *m, fsm_out_t *o);

/* 給人看的名字(印 log、除錯用) */
const char *fsm_state_name(fsm_state_t s);
const char *fsm_result_name(fsm_result_t r);

#endif /* FSM_H */
