/*============================================================================
 * 第 7 課:狀態機 ─ 行人穿越號誌路口  ─  C 語言版
 *============================================================================
 * 學習目標:
 *   1. 認識「有限狀態機 (FSM)」:用狀態 + 事件 + 轉移規則來組織韌體
 *   2. 學會把程式切成三層:輸入層 → 狀態機(純邏輯)→ 輸出層
 *   3. 體會為什麼這種寫法比「一堆 delay 的無窮迴圈」好維護(見 docs/11 §11.3)
 *   4. 用 UART 把每一次狀態轉移印出來,當成最實用的除錯手段
 *
 * 成果:一個會動的行人號誌。平常車道綠燈;按下按鈕後,號誌依序走完
 *       黃燈 → 行人通行 → 行人綠燈閃爍催促 → 全紅淨空 → 回到車道綠燈。
 *       全程 UART 會印出狀態轉移紀錄。
 *
 * 本課把邏輯放在 fsm.c / fsm.h(完全不碰硬體),這個 main.c 只負責接硬體。
 * 同一份 fsm.c 也能在電腦上跑:
 *     make -C ../../tools/fsm_sim run     # 模擬器(不用任何硬體!)
 *     make -C ../../tools/host_test test  # 單元測試
 *
 * 接線(5 顆 LED + 1 顆按鈕,全部 LED 都要串 220Ω):
 *   車道紅燈  P1.0 ----[220Ω]---->|---- GND
 *   車道黃燈  P1.1 ----[220Ω]---->|---- GND
 *   車道綠燈  P1.3 ----[220Ω]---->|---- GND
 *   行人紅燈  P1.6 ----[220Ω]---->|---- GND
 *   行人綠燈  P1.4 ----[220Ω]---->|---- GND
 *   行人按鈕  P1.5 ----[ 按鈕 ]---- GND      (用內部弱上拉,按下讀到 0)
 *   蜂鳴器    P0.4 ---- 有源蜂鳴器 ---- GND  (選用,不接也能跑)
 *   UART      P0.6 (TXD) ----> USB-TTL 的 RX,並且 GND 對接(選用但強烈建議)
 *
 *   💡 零件不夠?只接「行人綠燈 P1.4 + 按鈕 P1.5 + UART」也看得懂;
 *      完全沒零件的話,直接用上面的電腦模擬器把這一課學完。
 *===========================================================================*/

#include "N76E003.h"
#include "fsm.h"

/*---------------------------------------------------------------------------
 * 腳位定義(改接線時只要改這裡)
 *--------------------------------------------------------------------------*/
#define LED_VEH_R   P10      /* 車道紅 */
#define LED_VEH_Y   P11      /* 車道黃 */
#define LED_VEH_G   P13      /* 車道綠 */
#define LED_PED_R   P16      /* 行人紅 */
#define LED_PED_G   P14      /* 行人綠 */
#define BUZZER      P04      /* 蜂鳴器(選用) */
#define BTN         P15      /* 行人按鈕 */

/* 把「0/1 的位元組」寫進一支腳。寫成 if/else 最不會有型別轉換的疑慮。 */
#define SET_PIN(pin, on)   do { if (on) (pin) = 1; else (pin) = 0; } while (0)

#define DEBOUNCE_MS   20     /* 按鈕要連續穩定 20ms 才算一次真的變化 */

/*---------------------------------------------------------------------------
 * 中斷與主程式之間的「信箱」
 *   ISR 只負責「插旗子」,真正的工作留給主迴圈 —— ISR 要盡量短。
 *   兩邊都會碰到的變數一定要 volatile(同第 3 課)。
 *--------------------------------------------------------------------------*/
volatile unsigned char tick_flag = 0;   /* 1 = 又過了 100ms */
volatile unsigned char btn_flag  = 0;   /* 1 = 偵測到一次「按下」 */

/*---------------------------------------------------------------------------
 * Timer0 ISR:每 1ms 進來一次(預載值算法與第 3 課完全相同)
 *   在這裡做兩件事:① 累積成 100ms 的 tick  ② 按鈕去彈跳
 *--------------------------------------------------------------------------*/
void timer0_isr(void) __interrupt(1)
{
    static unsigned char ms      = 0;   /* 數到 100 = 一個 tick */
    static unsigned char deb     = 0;   /* 去彈跳計數 */
    static unsigned char stable  = 1;   /* 目前「確認過」的按鈕電位,1 = 放開 */
    unsigned char now;

    TH0 = 0xC1;                         /* 重載,維持精準的 1ms */
    TL0 = 0x80;

    /* ① 時間基準:1ms × 100 = 100ms */
    if (++ms >= 100)
    {
        ms = 0;
        tick_flag = 1;
    }

    /* ② 去彈跳:機械接點按下的瞬間會連續彈跳好幾毫秒,
          如果直接讀,一次按壓會被當成好幾次。所以要求電位
          連續 20ms 都是新值,才承認它真的變了。 */
    now = BTN;
    if (now != stable)
    {
        if (++deb >= DEBOUNCE_MS)
        {
            deb    = 0;
            stable = now;
            if (now == 0)               /* 低電位 = 按下(低電位有效) */
                btn_flag = 1;           /* 只在「按下的那一刻」產生事件 */
        }
    }
    else
    {
        deb = 0;                        /* 又跳回去了,重新計數 */
    }
}

/*---------------------------------------------------------------------------
 * 硬體初始化
 *--------------------------------------------------------------------------*/
void gpio_init(void)
{
    /* 5 顆 LED 的腳 → 推挽輸出(驅動力強,適合點 LED) */
    P1M1 &= ~((1 << 0) | (1 << 1) | (1 << 3) | (1 << 4) | (1 << 6));
    P1M2 |=  ((1 << 0) | (1 << 1) | (1 << 3) | (1 << 4) | (1 << 6));

    /* 蜂鳴器腳 P0.4 → 推挽輸出 */
    P0M1 &= ~(1 << 4);
    P0M2 |=  (1 << 4);

    /* 按鈕腳 P1.5 → 準雙向(用內部弱上拉,免外接電阻;同第 2 課) */
    P1M1 &= ~(1 << 5);
    P1M2 &= ~(1 << 5);
    BTN   = 1;                /* 準雙向腳讀取前要先寫 1,才能被外界拉低 */
}

void timer0_init(void)
{
    TMOD &= ~0x0F;
    TMOD |=  0x01;            /* Timer0 → 模式 1(16 位元) */
    CKCON |= 0x08;            /* T0M = 1:Timer0 吃完整 16MHz */
    TH0 = 0xC1;               /* 65536 - 16000 = 0xC180 → 每 1ms 溢位 */
    TL0 = 0x80;
    ET0 = 1;                  /* 開 Timer0 中斷 */
    EA  = 1;                  /* 開總中斷 */
    TR0 = 1;                  /* 啟動 */
}

/*---------------------------------------------------------------------------
 * UART(與第 4 課相同,拿來印狀態轉移紀錄;9600 8N1)
 *--------------------------------------------------------------------------*/
void uart_init(void)
{
    P0M1 &= ~((1 << 6) | (1 << 7));
    P0M2 &= ~((1 << 6) | (1 << 7));
    SCON  = 0x50;
    TMOD &= ~0xF0;
    TMOD |=  0x20;            /* Timer1 → 模式2,當鮑率產生器 */
    PCON  |= 0x80;            /* SMOD = 1 */
    CKCON |= 0x10;            /* T1M = 1 */
    T3CON &= ~0x20;           /* 鮑率時脈來源選 Timer1 */
    TH1 = 0x98;               /* ≈ 9600 bps */
    TL1 = 0x98;
    TR1 = 1;
}

void uart_putc(char c)
{
    SBUF = c;
    while (!TI)
        ;
    TI = 0;
}

void uart_puts(const char *s)
{
    while (*s)
        uart_putc(*s++);
}

/*---------------------------------------------------------------------------
 * 輸出層:把狀態機算出來的「輸出快照」真正送到腳位上
 *   注意這裡完全沒有任何 if (state == ...) —— 燈號規則全在 fsm_outputs()。
 *--------------------------------------------------------------------------*/
void drive_outputs(const fsm_out_t *o)
{
    SET_PIN(LED_VEH_R, o->veh_red);
    SET_PIN(LED_VEH_Y, o->veh_yellow);
    SET_PIN(LED_VEH_G, o->veh_green);
    SET_PIN(LED_PED_R, o->ped_red);
    SET_PIN(LED_PED_G, o->ped_green);
    SET_PIN(BUZZER,    o->buzzer);
}

/* 印一行紀錄:事件的處理結果 + 現在的狀態 */
void report(fsm_result_t r, const fsm_t *m, const char *ev_name)
{
    uart_puts("[");
    uart_puts(ev_name);
    uart_puts("] ");
    uart_puts(fsm_result_name(r));
    uart_puts(" -> ");
    uart_puts(fsm_state_name(m->state));
    uart_puts("\r\n");
}

/*===========================================================================
 * 主程式:短得不像話 —— 這正是狀態機架構的賣點
 *==========================================================================*/
void main(void)
{
    fsm_t     machine;        /* 狀態機的全部記憶,就這一個變數 */
    fsm_out_t out;            /* 這一輪該有的輸出 */
    fsm_result_t r;

    gpio_init();
    uart_init();

    fsm_init(&machine);       /* 開機:回到車道綠燈 */
    fsm_outputs(&machine, &out);
    drive_outputs(&out);      /* 先把開機的燈號點出來 */

    uart_puts("\r\n=== N76E003 行人穿越號誌 (狀態機範例) ===\r\n");
    uart_puts("按下 P1.5 的按鈕來申請過馬路\r\n");
    report(FSM_CHANGED, &machine, "開機");

    timer0_init();            /* 最後才開中斷,確保一切就緒 */

    while (1)
    {
        /* ---- 輸入層:把硬體訊號轉成「事件」 ---- */
        if (btn_flag)
        {
            btn_flag = 0;                              /* 旗子要自己清掉 */
            r = fsm_handle(&machine, EV_BUTTON);       /* 餵給狀態機 */
            report(r, &machine, "按鈕");
        }

        if (tick_flag)
        {
            tick_flag = 0;
            r = fsm_handle(&machine, EV_TICK);
            if (r == FSM_CHANGED)                      /* 只在轉移時印,免得洗版 */
                report(r, &machine, "時間");

            /* ---- 輸出層:每個 tick 都更新一次(閃爍才會動) ---- */
            fsm_outputs(&machine, &out);
            drive_outputs(&out);
        }

        /* 這裡還很空 —— 想再加功能(讀 ADC、第二個路口…)直接加在旁邊,
           不會把現有的號誌邏輯打亂。這就是不用 delay() 的好處。 */
    }
}
