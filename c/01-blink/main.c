/*============================================================================
 * 第 1 課:LED 閃爍 (Blink)  ─  C 語言版
 *============================================================================
 * 學習目標:
 *   1. 認識 GPIO (通用輸入輸出腳位),學會把一支腳設成「輸出」
 *   2. 用程式控制腳位輸出高電位 / 低電位,讓 LED 亮 / 滅
 *   3. 用簡單的「軟體延時」做出看得見的閃爍
 *
 * 接線 (本教材預設):
 *   LED 正極(長腳)──► 220Ω 電阻 ──► 腳位 P1.4
 *   LED 負極(短腳)──► GND
 *   → 當 P1.4 輸出「高電位(1)」時 LED 亮,輸出「低電位(0)」時 LED 滅。
 *
 *   註:若你用開發板上「內建的 LED」,它的亮滅可能是相反的(低電位才亮),
 *       這時把下面的 LED_ON / LED_OFF 對調即可。
 *===========================================================================*/

#include "N76E003.h"

/* 把「LED」這個名字對應到 P1.4 這支腳,之後改腳位只要改這一行 */
#define LED        P14

#define LED_ON     1      /* 高電位點亮(外接 LED 接法)*/
#define LED_OFF    0

/*----------------------------------------------------------------------------
 * 軟體延時:單純讓 CPU 空轉數個迴圈來拖時間。
 * 這種延時「不精準」,只是先讓你看到閃爍;第 3 課會用 Timer 做精準延時。
 *   volatile 關鍵字:告訴編譯器「這個變數會一直變,不要把迴圈最佳化刪掉」。
 *---------------------------------------------------------------------------*/
void delay(void)
{
    volatile unsigned int i, j;
    for (i = 0; i < 300; i++)
        for (j = 0; j < 120; j++)
            ;                      /* 什麼都不做,只是消耗時間 */
}

/*----------------------------------------------------------------------------
 * 把 P1.4 設定成「推挽輸出 (Push-Pull)」。
 *   GPIO 模式由 P1M1、P1M2 兩個暫存器的「同一個位元」共同決定:
 *     P1M1.4 = 0, P1M2.4 = 1  → 推挽輸出(強力輸出,適合驅動 LED)
 *   這裡用「位元運算」只改第 4 位,不影響其他腳位:
 *     &= ~(1<<4)  → 把第 4 位清為 0
 *     |=  (1<<4)  → 把第 4 位設為 1
 *---------------------------------------------------------------------------*/
void gpio_init(void)
{
    P1M1 &= ~(1 << 4);     /* P1M1.4 = 0 */
    P1M2 |=  (1 << 4);     /* P1M2.4 = 1 → 推挽輸出 */
}

void main(void)
{
    gpio_init();

    while (1)              /* 微控制器的程式永遠不會結束,用無窮迴圈 */
    {
        LED = LED_ON;      /* 點亮 LED */
        delay();
        LED = LED_OFF;     /* 熄滅 LED */
        delay();
    }
}
