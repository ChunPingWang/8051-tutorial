/*============================================================================
 * 第 6 課:PWM 呼吸燈 ─ 用硬體控制 LED 亮度  ─  C 語言版
 *============================================================================
 * 學習目標:
 *   1. 認識 PWM(脈衝寬度調變):用「開關的時間比例」做出類比般的效果
 *   2. 設定 N76E003 的硬體 PWM,從 PWM0 輸出到 P1.2
 *   3. 連續改變工作週期 (duty),做出 LED 由暗漸亮、再漸暗的「呼吸」效果
 *
 * 成果:接在 P1.2 的 LED 會像呼吸一樣,亮度平滑地增強、減弱、循環。
 *
 * 接線:
 *   P1.2 ──► 220Ω ──► LED 長腳(+),LED 短腳(−)──► GND
 *   注意:PWM0 這個通道「固定」對應 P1.2 這支腳(腳位複用),所以這一課
 *         的 LED 要接 P1.2,而不是前幾課的 P1.4。
 *
 * 原理(詳見 docs/08-PWM.md):
 *   PWM 以很快的速度把腳位開/關。一個週期裡「開」佔的比例叫工作週期 (duty)。
 *   duty 越大,LED 平均拿到的電越多 → 看起來越亮。因為切換快到眼睛看不出
 *   閃爍,我們只感覺到「亮度」在變。
 *===========================================================================*/

#include "N76E003.h"

/* 設定 PWM0 的工作週期(0 = 全暗,255 = 全亮)*/
void pwm_set_duty(unsigned char duty)
{
    PWM0H = 0x00;        /* 工作週期高位元組(我們只用 8 位元,高位固定 0)*/
    PWM0L = duty;        /* 工作週期低位元組 */
    LOAD  = 1;           /* 寫 1 讓新的 duty 在下個週期生效(硬體會自動清除)*/
}

void pwm_init(void)
{
    /* P1.2 設推挽輸出(PWM 要能強力驅動)*/
    P1M1 &= ~(1 << 2);
    P1M2 |=  (1 << 2);

    PWMCON0 = 0x00;      /* 先清空控制暫存器 */
    PWMCON1 = 0x07;      /* PWM 時脈 = Fsys/128,邊緣對齊、各通道獨立模式 */
    PNP     = 0x00;      /* 輸出極性:正常(duty 越大、高電位時間越長 → 越亮)*/
    PIOCON0 = 0x01;      /* 把 PWM0 的輸出接到 P1.2 這支腳 */

    /* PWM 週期 = {PWMPH, PWMPL} + 1。設 255 → 一個週期切成 256 階 */
    PWMPH = 0x00;
    PWMPL = 0xFF;

    pwm_set_duty(0);     /* 初始亮度 0 */

    PWMRUN = 1;          /* 啟動 PWM 計數器 */
}

/* 很短的延時,決定「呼吸」變化的快慢 */
void step_delay(void)
{
    volatile unsigned int i;
    for (i = 0; i < 400; i++)
        ;
}

void main(void)
{
    unsigned int d;

    pwm_init();

    while (1)
    {
        for (d = 0; d <= 255; d++)      /* 由暗漸亮 */
        {
            pwm_set_duty((unsigned char)d);
            step_delay();
        }
        for (d = 255; d > 0; d--)       /* 由亮漸暗 */
        {
            pwm_set_duty((unsigned char)d);
            step_delay();
        }
    }
}
