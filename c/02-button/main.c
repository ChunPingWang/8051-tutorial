/*============================================================================
 * 第 2 課:按鈕控制 LED  ─  C 語言版
 *============================================================================
 * 學習目標:
 *   1. 把一支腳設成「輸入」,讀取它是高電位還是低電位
 *   2. 用 if 判斷按鈕狀態,決定 LED 亮或滅
 *   3. 認識「低電位有效 (active-low)」與準雙向腳的內部弱上拉
 *
 * 接線:
 *   LED : P1.4 --> 220Ω --> LED(長腳),LED(短腳)--> GND   (按下才亮)
 *   按鈕: P1.5 ──────[ 按鈕 ]────── GND
 *         (利用 N76E003 準雙向腳的「內部弱上拉」,不必外接上拉電阻)
 *
 *   → 放開按鈕:P1.5 被內部弱上拉拉到高電位,讀到 1
 *   → 按下按鈕:P1.5 直接接到 GND,讀到 0      ← 這就是「低電位有效」
 *===========================================================================*/

#include "N76E003.h"

#define LED   P14        /* 輸出:接 LED */
#define SW    P15        /* 輸入:接按鈕 (switch) */

void gpio_init(void)
{
    /* P1.4 → 推挽輸出(驅動 LED)*/
    P1M1 &= ~(1 << 4);
    P1M2 |=  (1 << 4);

    /* P1.5 → 準雙向(讀按鈕,使用內部弱上拉)。開機預設就是這個模式,
       這裡明確寫出來是為了讓你看清楚每支腳的設定。 */
    P1M1 &= ~(1 << 5);
    P1M2 &= ~(1 << 5);

    SW = 1;              /* 準雙向腳在「讀取」前要先寫 1,才能被外界拉低 */
}

void main(void)
{
    gpio_init();

    while (1)
    {
        if (SW == 0)     /* 按鈕被按下(低電位)*/
            LED = 1;     /* 點亮 LED */
        else             /* 按鈕放開(高電位)*/
            LED = 0;     /* 熄滅 LED */
    }
}
